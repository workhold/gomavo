export type MessageKey = keyof typeof dictionary

export function loadLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    return saved === 'zh-CN' || saved === 'en-US' ? saved : DEFAULT_LOCALE
  } catch {
    return DEFAULT_LOCALE
  }
}

export function saveLocale(locale: Locale): void {
  try {
    localStorage.setItem(STORAGE_KEY, locale)
  } catch {
    // The caller's in-memory locale remains usable when storage is unavailable.
  }
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values?: Record<string, string | number>,
): string {
  const message: string = dictionary[key]?.[locale] ?? key
  if (!values) return message
  return message.replace(/\{([^{}]+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  )
}
